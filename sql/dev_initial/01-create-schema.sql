alter sequence application_id_seq owned by application.id;
-- alter sequence public.application_registry_id_seq owner to femto;
alter sequence application_registry_id_seq owned by application_registry.id;
-- alter sequence public.merchant_channel_id_seq owner to femto;
alter sequence merchant_channel_id_seq owned by merchant_channel.id;
-- alter sequence sequencers_id_seq owner to femto;
alter sequence sequencers_id_seq owned by sequencers.id;





